-- 1. Create Tbl04Role
CREATE TABLE public."Tbl04Role" (
    role_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_code text UNIQUE NOT NULL,
    role_name text NOT NULL,
    level_number int NOT NULL,
    description text
);

